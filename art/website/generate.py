#!/usr/bin/env python3
"""
Regenerates the website's icons (docs/icons.svg, one <symbol> per icon) from
Material Symbols — Rounded, weight 400, outlined — the same glyphs as the
app's icons (art/material-symbols/generate.py), and the favicon
(docs/favicon.svg) from the brand mark (art/brand/currencix-mark.svg).

    npm pack @material-symbols/svg-400@0.48.1 && tar xzf material-symbols-svg-400-*.tgz
    python3 art/website/generate.py package/rounded

A page draws an icon with <svg class="icon"><use href="icons.svg#name"/></svg>.
To add one, add its Material Symbols name to ICONS and rerun.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs"
MARK = ROOT / "art" / "brand" / "currencix-mark.svg"
SYMBOLS_VERSION = "0.48.1"

ICONS = sorted({
    # conversion
    "account_balance", "alt_route", "star", "history", "content_paste", "touch_app",
    # calculator
    "calculate", "dialpad", "keyboard",
    # fees
    "percent", "credit_card",
    # rates, charts, alerts
    "event", "show_chart", "query_stats", "notifications", "table_chart",
    # cart
    "shopping_cart", "luggage", "receipt_long", "ios_share",
    # look and feel
    "palette", "contrast", "devices", "translate", "widgets", "accessibility_new",
    # privacy and security
    "block", "lock", "visibility_off", "save", "shield",
    # open source and links
    "swap_horiz", "backspace",
})

PATH = re.compile(r'<path d="([^"]+)"/>')


def sprite(symbols: pathlib.Path) -> str:
    out = [
        '<svg xmlns="http://www.w3.org/2000/svg">',
        f"<!-- Material Symbols Rounded {SYMBOLS_VERSION}, (c) Google, Apache-2.0. Generated by art/website/generate.py. -->",
    ]
    for name in ICONS:
        svg = (symbols / f"{name}.svg").read_text()
        paths = "".join(f'<path d="{d}"/>' for d in PATH.findall(svg))
        out.append(f'<symbol id="{name}" viewBox="0 -960 960 960">{paths}</symbol>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


# The mark's green, brass and × in the light page's colors, and the ink
# page's in dark mode (the same pairs as the splash, res/values*/colors.xml).
FAVICON_STYLE = (
    "<style>.g{fill:#5E9A40;stroke:#5E9A40}.b{fill:#9C7C3E;stroke:#9C7C3E}.x{stroke:#1C1B1F}"
    "@media (prefers-color-scheme:dark){.g{fill:#85BB65;stroke:#85BB65}.b{fill:#B8985B;stroke:#B8985B}.x{stroke:#EFEAE0}}</style>"
)


def favicon() -> str:
    svg = MARK.read_text()
    paths = re.findall(r"<path [^>]*/>", svg)
    green, brass, cross = paths
    strip = lambda p: re.sub(r' (fill|stroke)="#[0-9A-Fa-f]{6}"', "", p)
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72">'
        + FAVICON_STYLE
        + strip(green).replace("<path ", '<path class="g" ')
        + strip(brass).replace("<path ", '<path class="b" ')
        + strip(cross).replace("<path ", '<path class="x" ')
        + "</svg>\n"
    )


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    (DOCS / "icons.svg").write_text(sprite(pathlib.Path(sys.argv[1])))
    (DOCS / "favicon.svg").write_text(favicon())


if __name__ == "__main__":
    main()
