#!/usr/bin/env python3
"""
Draws the CurrenciX mark, two arrows swapping around a "×", and writes
everything made from it:

- app/src/main/res/values/brand_mark.xml: its paths, which the launcher
  icon (ic_launcher_foreground, ic_launcher_monochrome) and the splash
  screen (brand_mark) draw;
- art/brand/currencix-mark.svg (the mark alone) and art/brand/ic_launcher.svg
  (the launcher icon, on ink);
- fastlane's store icon (images/icon.png, 512 px), when cairosvg is
  installed (pip install cairosvg).

    python3 art/brand/generate.py

The mark sits in the 108-unit adaptive-icon canvas, scaled to stay inside
its 66-unit safe circle so no launcher mask crops it. To change it, change
the numbers below and rerun.
"""
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
VALUES = ROOT / "app/src/main/res/values/brand_mark.xml"
STORE_ICON = ROOT / "fastlane/metadata/android/en-US/images/icon.png"
STORE_ICON_PX = 512

CANVAS = 108
CENTRE = CANVAS / 2
# Furthest the mark reaches from the centre (an arrowhead's barb) is fitted
# to SAFE_RADIUS; the geometry below is in "design units" before that.
SAFE_RADIUS = 32
TILT = -45  # degrees; the arrows run along the diagonal

RING_RADIUS = 28
RING_WIDTH = 7
HEAD_LENGTH = 13  # from the head's base to its tip, along the tangent
HEAD_HALF_WIDTH = 9.5  # base half-width, across the ring
# Clockwise, in degrees (0 = 3 o'clock, y down), before TILT: where each
# arrow starts and where its head's base is.
TOP_ARC = (198, 312)
BOTTOM_ARC = (18, 132)
CROSS_SIZE = 17
CROSS_WIDTH = 6.5
# Width of the outline that slightly rounds the arrowheads' corners.
ARROW_ROUNDING = 1

SCALE = SAFE_RADIUS / (RING_RADIUS + HEAD_HALF_WIDTH)

INK = "#131311"
INK_FOREGROUND = "#EFEAE0"
BILL_GREEN = "#85BB65"
BRASS = "#B8985B"


def point(radius: float, degrees: float) -> tuple[float, float]:
    a = math.radians(degrees)
    return CENTRE + radius * math.cos(a), CENTRE + radius * math.sin(a)


def fmt(p: tuple[float, float]) -> str:
    return f"{p[0]:.2f},{p[1]:.2f}"


def arrow(start: float, head_base: float) -> str:
    """A ring segment with a round tail, ending in an isosceles head whose
    base is across the ring at [head_base] and whose tip points along the
    ring's tangent there: one closed shape, so the head is part of the arc."""
    start, head_base = start + TILT, head_base + TILT
    r, w = RING_RADIUS * SCALE, RING_WIDTH * SCALE
    half, length = HEAD_HALF_WIDTH * SCALE, HEAD_LENGTH * SCALE
    outer, inner = r + w / 2, r - w / 2
    base = point(r, head_base)
    tangent = math.radians(head_base + 90)
    tip = (base[0] + length * math.cos(tangent), base[1] + length * math.sin(tangent))
    large = 1 if head_base - start > 180 else 0
    return (
        f"M{fmt(point(outer, start))} A{outer:.4f},{outer:.4f} 0 {large} 1 {fmt(point(outer, head_base))} "
        f"L{fmt(point(r + half, head_base))} L{fmt(tip)} L{fmt(point(r - half, head_base))} "
        f"L{fmt(point(inner, head_base))} A{inner:.4f},{inner:.4f} 0 {large} 0 {fmt(point(inner, start))} "
        f"A{w / 2:.4f},{w / 2:.4f} 0 0 1 {fmt(point(outer, start))} Z"
    )


def cross() -> str:
    lo, hi = CENTRE - CROSS_SIZE * SCALE / 2, CENTRE + CROSS_SIZE * SCALE / 2
    return f"M{lo:.2f},{lo:.2f} L{hi:.2f},{hi:.2f} M{hi:.2f},{lo:.2f} L{lo:.2f},{hi:.2f}"


TOP, BOTTOM, CROSS = arrow(*TOP_ARC), arrow(*BOTTOM_ARC), cross()
ROUNDING, CROSS_STROKE = ARROW_ROUNDING * SCALE, CROSS_WIDTH * SCALE


def values_xml() -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!--
    Generated by art/brand/generate.py; change it there.

    The CurrenciX mark: two arrows swapping around a "×", the green one (the
    currency you have) and the brass one (the one you get). One shape for the
    launcher icon (ic_launcher_foreground, ic_launcher_monochrome) and the
    splash screen (brand_mark), so the paths live here once. Drawn in the
    108dp adaptive-icon canvas, inside its 66dp safe circle.
-->
<resources>
    <string name="brand_mark_arrow_top" translatable="false">{TOP}</string>
    <string name="brand_mark_arrow_bottom" translatable="false">{BOTTOM}</string>
    <string name="brand_mark_cross" translatable="false">{CROSS}</string>
    <!-- Line widths: the outline rounding the arrowheads, and the cross. -->
    <item name="brand_mark_arrow_round" format="float" type="dimen">{ROUNDING:.2f}</item>
    <item name="brand_mark_cross_width" format="float" type="dimen">{CROSS_STROKE:.2f}</item>
</resources>
"""


def svg(background: str | None) -> str:
    def arrow_path(d: str, color: str) -> str:
        return (
            f'  <path d="{d}" fill="{color}" stroke="{color}" '
            f'stroke-width="{ROUNDING:.2f}" stroke-linejoin="round"/>\n'
        )

    back = f'  <rect width="{CANVAS}" height="{CANVAS}" fill="{background}"/>\n' if background else ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {CANVAS} {CANVAS}" '
        f'width="{CANVAS * 4}" height="{CANVAS * 4}">\n'
        + back
        + arrow_path(TOP, BILL_GREEN)
        + arrow_path(BOTTOM, BRASS)
        + f'  <path d="{CROSS}" fill="none" stroke="{INK_FOREGROUND}" '
        f'stroke-width="{CROSS_STROKE:.2f}" stroke-linecap="round"/>\n'
        "</svg>\n"
    )


def main() -> None:
    here = pathlib.Path(__file__).parent
    VALUES.write_text(values_xml())
    (here / "currencix-mark.svg").write_text(svg(None))
    launcher = svg(INK)
    (here / "ic_launcher.svg").write_text(launcher)
    try:
        import cairosvg
    except ImportError:
        print("cairosvg isn't installed; store icon not written")
        return
    cairosvg.svg2png(
        bytestring=launcher.encode(),
        write_to=str(STORE_ICON),
        output_width=STORE_ICON_PX,
        output_height=STORE_ICON_PX,
    )


if __name__ == "__main__":
    main()
