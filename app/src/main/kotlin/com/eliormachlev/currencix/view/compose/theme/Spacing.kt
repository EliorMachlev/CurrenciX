package com.eliormachlev.currencix.view.compose.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * The app's spacing scale, for paddings and gaps. A file names its spacing
 * for what it's for (`ROW_GAP`, `CARD_PADDING`) and takes the value from
 * here, so the rhythm stays consistent across screens and changing it is one
 * edit. Sizes, radii and strokes aren't spacing and stay with their files.
 */
object Spacing {
    val Hairline: Dp = 2.dp
    val Tiny: Dp = 4.dp
    val XSmall: Dp = 6.dp
    val Small: Dp = 8.dp
    val SmallPlus: Dp = 10.dp
    val Medium: Dp = 12.dp
    val MediumPlus: Dp = 14.dp
    val Large: Dp = 16.dp
    val XLarge: Dp = 20.dp
    val XXLarge: Dp = 24.dp
}
